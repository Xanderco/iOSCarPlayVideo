                    PersistenceController.shared.saveWidgets(savedWidgets)
                }
            }
            .sheet(isPresented: $showingDoodleEditor) {
                DoodleEditorView()
            }
            .alert(WidgetsHomeCopy.carPlayGuideAlertTitleKey, isPresented: $showingCarPlayGuide) {
                Button(WidgetsHomeCopy.gotItButtonKey, role: .cancel) {}
            } message: {
                Text(WidgetsHomeCopy.carPlayGuideAlertMessageKey)
            }
            .onAppear {
                let loaded = PersistenceController.shared.loadWidgets()
                if loaded.isEmpty {
                    savedWidgets = WidgetsHomeDefaults.starterWidgets
                    PersistenceController.shared.saveWidgets(savedWidgets)
                } else {
                    savedWidgets = loaded
                }
            }
        }
